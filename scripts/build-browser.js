#!/usr/bin/env node

/*
** Minimal CommonJS bundler for the browser build.
**
** It resolves the static `require("literal")` calls in src/ and in the few
** npm modules that run in the browser (sprintf-js), stubs Node built-ins and
** emits an IIFE that exposes the package as `globalThis.fengari`.
**
** Usage: node scripts/build-browser.js [--out=dist/fengari.js]
*/

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ENTRY = "src/fengari.js";

let output = path.join(ROOT, "dist", "fengari.js");
for (const arg of process.argv.slice(2)) {
    const m = /^--out=(.+)$/.exec(arg);
    if (m)
        output = path.resolve(ROOT, m[1]);
    else {
        console.error(`unknown argument: ${arg}`);
        process.exit(2);
    }
}

const NODE_BUILTINS = new Set([
    "fs", "path", "os", "child_process", "tmp", "readline-sync"
]);

const modules = new Map();

const relative_id = function(full) {
    return path.relative(ROOT, full).split(path.sep).join("/");
};

const resolve_package = function(request) {
    let base = path.join(ROOT, "node_modules", request);
    let pkg = path.join(base, "package.json");
    if (fs.existsSync(pkg)) {
        let info = JSON.parse(fs.readFileSync(pkg, "utf8"));
        let main = info.main || "index.js";
        let full = path.join(base, main);
        if (!fs.existsSync(full) && fs.existsSync(full + ".js"))
            full += ".js";
        return relative_id(full);
    }
    if (fs.existsSync(base + ".js"))
        return relative_id(base + ".js");
    if (fs.existsSync(path.join(base, "index.js")))
        return relative_id(path.join(base, "index.js"));
    throw new Error(`cannot resolve package '${request}'`);
};

const resolve_request = function(from, request) {
    if (request.startsWith(".")) {
        let full = path.resolve(path.dirname(path.join(ROOT, from)), request);
        if (fs.existsSync(full) && fs.statSync(full).isDirectory())
            full = path.join(full, "index.js");
        else if (!fs.existsSync(full) && fs.existsSync(full + ".js"))
            full += ".js";
        if (!fs.existsSync(full))
            throw new Error(`cannot resolve '${request}' from ${from}`);
        return relative_id(full);
    }
    if (NODE_BUILTINS.has(request))
        return `__stub__/${request}`;
    return resolve_package(request);
};

const add_module = function(id) {
    if (modules.has(id))
        return;
    if (id.startsWith("__stub__/")) {
        modules.set(id, { stub: id.slice("__stub__/".length) });
        return;
    }
    /* reserve the id before scanning so require cycles terminate */
    modules.set(id, { pending: true });
    try {
        let full = path.join(ROOT, id);
        let source = fs.readFileSync(full, "utf8");
        let map = {};
        let re = /\brequire\s*\(\s*(['"])([^'"]+)\1\s*\)/g;
        let m;
        while ((m = re.exec(source))) {
            let request = m[2];
            let target = resolve_request(id, request);
            map[request] = target;
            add_module(target);
        }
        modules.set(id, { source: source, map: map });
    } catch (e) {
        modules.delete(id);
        throw e;
    }
};

add_module(ENTRY);

let out = "/* Generated by scripts/build-browser.js. Do not edit. */\n";
out += "(function(global) {\n";
out += '"use strict";\n';
out += "var modules = {\n";
for (const [id, mod] of modules) {
    if (mod.stub) {
        out += `${JSON.stringify(id)}: function(module, exports, require) {\n`;
        out += `    throw new Error(${JSON.stringify(mod.stub + " is not available in the browser")});\n`;
        out += "},\n";
    } else {
        out += `${JSON.stringify(id)}: function(module, exports, __require) {\n`;
        out += "    var map = " + JSON.stringify(mod.map) + ";\n";
        out += "    var require = function(name) {\n";
        out += "        if (Object.prototype.hasOwnProperty.call(map, name))\n";
        out += "            return __require(map[name]);\n";
        out += "        throw new Error(\"Cannot find module '\" + name + \"'\");\n";
        out += "    };\n";
        out += mod.source + "\n";
        out += "},\n";
    }
}
out += "};\n";
out += "var cache = {};\n";
out += "function req(id) {\n";
out += "    if (cache[id]) return cache[id].exports;\n";
out += "    var module = cache[id] = { exports: {} };\n";
out += "    modules[id](module, module.exports, req);\n";
out += "    return module.exports;\n";
out += "}\n";
out += `var fengari = req(${JSON.stringify(ENTRY)});\n`;
out += "if (typeof module === \"object\" && module.exports) module.exports = fengari;\n";
out += "else global.fengari = fengari;\n";
out += "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n";

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, out);
console.log(`${relative_id(output)} (${modules.size} modules, ${(out.length / 1024).toFixed(0)} KiB)`);
